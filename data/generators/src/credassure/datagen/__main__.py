"""``make data``: regenerate data/frozen/v1 from the seed. Same seed, same bytes.

Refuses to run once ``data/frozen/v1/FROZEN`` exists (G1); later changes go to v2.

``python -m credassure.datagen hr-db`` (``make hr-db``) only rebuilds the gitignored ``hr.db``
from the frozen, hashed ``hr/profiles.json``. It is allowed after the freeze, so a fresh clone or
CI can run the tests that read the HR store; ``hr.db`` is not in SHA256SUMS.
"""

import hashlib
import json
import shutil
import sys
from collections import Counter

from . import cases, fixtures, hr, kfs, offers, policies
from .common import OUT, SEED, write_json, write_text

HASHED_EXCLUDE = {"hr.db", "SHA256SUMS"}


def _plants_md(plants: list[dict[str, str]]) -> str:
    counts = Counter((p["dataset"], p["plant"]) for p in plants)
    lines = [
        "# PLANTS — synthetic data v1",
        "",
        f"Generated by `make data` (seed {SEED}). Every planted item and its plant type. "
        "Expected answers come from `evaluation/gold`, not from this file.",
        "",
        "## Counts",
        "",
        "| Dataset | Plant | Count |",
        "|---|---|---|",
    ]
    lines += [f"| {d} | {p} | {n} |" for (d, p), n in sorted(counts.items())]
    lines += ["", "## Items", "", "| Item | Dataset | Plant |", "|---|---|---|"]
    lines += [f"| {p['id']} | {p['dataset']} | {p['plant']} |" for p in plants]
    return "\n".join(lines) + "\n"


def main() -> int:
    if (OUT / "FROZEN").exists():
        print(f"{OUT} is frozen (G1). Generate a new version instead.", file=sys.stderr)
        return 1
    shutil.rmtree(OUT, ignore_errors=True)
    plants = hr.generate()
    designs, case_plants = cases.generate()
    records, offer_plants = offers.generate(designs)
    plants += case_plants + offer_plants + kfs.generate(records) + policies.generate()
    plants += fixtures.generate()
    write_json(OUT / "_design" / "designs.json", designs)  # design intent; gold must not read it
    write_json(OUT / "plants.json", plants)
    write_text(OUT / "PLANTS.md", _plants_md(plants))
    files = sorted(p for p in OUT.rglob("*") if p.is_file() and p.name not in HASHED_EXCLUDE)
    write_text(
        OUT / "SHA256SUMS",
        "".join(
            f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(OUT).as_posix()}\n"
            for p in files
        ),
    )
    print(f"wrote {len(files)} files to {OUT}")
    return 0


def build_hr_db() -> int:
    """Rebuild hr.db from the frozen profiles; never touches a hashed file."""
    profiles = json.loads((OUT / "hr" / "profiles.json").read_text(encoding="utf-8"))
    hr.build_db(profiles)
    print(f"wrote {OUT / 'hr.db'} ({len(profiles)} profiles)")
    return 0


if __name__ == "__main__":
    if sys.argv[1:] == ["hr-db"]:
        raise SystemExit(build_hr_db())
    raise SystemExit(main())
