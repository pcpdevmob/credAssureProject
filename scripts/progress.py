"""Generate PROGRESS.md from docs/progress/ (README §11).

Nobody edits PROGRESS.md by hand. Each PR adds one entry file in docs/progress/entries/ and updates
its own module file in docs/progress/modules/; this script builds PROGRESS.md from:

- docs/progress/gates.md      gate checklist (edited only at gate time)
- docs/progress/modules/*.md  one file per module (owner, phases, status, open items)
- docs/progress/entries/*.md  one file per PR (YAML-style front matter + Built / Decisions / Open)
- docs/progress/HISTORY.md    everything before 2026-11-18, frozen (linked, not copied)

Usage:
    python scripts/progress.py           # write PROGRESS.md
    python scripts/progress.py --check   # fail if PROGRESS.md is stale or an entry is invalid

Output is deterministic: the same files give byte-identical output (no clock, sorted inputs).
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROGRESS_DIR = Path("docs/progress")
OUTPUT = Path("PROGRESS.md")

MODULES: tuple[str, ...] = (
    "UI",
    "Copilot",
    "Authentication",
    "Responsible AI",
    "AI Security and Guardrails",
    "Deployment",
    "Documentation",
    "Evaluation",
)
# Module name -> module file stem in docs/progress/modules/.
MODULE_FILES: dict[str, str] = {
    "UI": "ui",
    "Copilot": "copilot",
    "Authentication": "auth",
    "Responsible AI": "rai",
    "AI Security and Guardrails": "guardrails",
    "Deployment": "deployment",
    "Documentation": "docs",
    "Evaluation": "evaluation",
}
STATUSES: tuple[str, ...] = ("done", "in_progress", "blocked")
REQUIRED: tuple[str, ...] = ("phase", "step", "module", "owner", "commits", "evals", "status")
LIST_FIELDS: frozenset[str] = frozenset({"commits", "evals"})

# YYYY-MM-DD-<phase>-<step>-<slug>-<owner>.md ; slug may contain hyphens, owner may not.
FILENAME_RE = re.compile(
    r"^(?P<date>\d{4}-\d{2}-\d{2})-(?P<phase>[A-Za-z0-9]+)-(?P<step>[0-9][0-9A-Za-z.]*)"
    r"-(?P<slug>[a-z0-9][a-z0-9-]*)-(?P<owner>[a-z0-9]+)\.md$"
)
HEADER = (
    "<!-- GENERATED by make progress — do not edit by hand. -->\n"
    "# CredAssure — Progress\n\n"
    "> **GENERATED by `make progress` — do not edit by hand.** To record progress, add one "
    "entry file in `docs/progress/entries/` (copy `TEMPLATE.md`), update your module file in "
    "`docs/progress/modules/`, then run `make progress`. Process: README §11.\n"
)


class EntryError(ValueError):
    """An entry file breaks the format; the message names the file and the field."""


@dataclass(frozen=True)
class Entry:
    path: Path
    date: str
    phase: str
    step: str
    module: str
    owner: str
    status: str
    commits: tuple[str, ...]
    evals: tuple[str, ...]
    open_items: tuple[str, ...] = field(default=())


@dataclass(frozen=True)
class Module:
    name: str
    path: Path
    owner: str
    phases: str
    status: str


def _parse_value(raw: str) -> str | tuple[str, ...]:
    value = raw.split(" #", 1)[0].strip()
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        if not inner:
            return ()
        return tuple(part.strip().strip("\"'") for part in inner.split(",") if part.strip())
    return value.strip("\"'")


def parse_front_matter(text: str, name: str) -> tuple[dict[str, str | tuple[str, ...]], str]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise EntryError(f"{name}: front matter must start with '---' on line 1")
    try:
        end = next(i for i, line in enumerate(lines[1:], start=1) if line.strip() == "---")
    except StopIteration as exc:
        raise EntryError(f"{name}: front matter has no closing '---'") from exc
    data: dict[str, str | tuple[str, ...]] = {}
    for number, line in enumerate(lines[1:end], start=2):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if ":" not in stripped:
            raise EntryError(f"{name}: line {number} is not 'key: value'")
        key, raw = stripped.split(":", 1)
        data[key.strip()] = _parse_value(raw)
    return data, "\n".join(lines[end + 1 :])


def _open_items(body: str) -> tuple[str, ...]:
    items: list[str] = []
    for line in body.splitlines():
        match = re.match(r"^\s*[-*]\s*Open:\s*(.+)$", line)
        if match:
            text = match.group(1).strip()
            if text.lower().rstrip(".") not in {"none", "nothing", "n/a", "-"}:
                items.append(text)
    return tuple(items)


def parse_entry(path: Path) -> Entry:
    name = path.name
    match = FILENAME_RE.match(name)
    if not match:
        raise EntryError(
            f"{name}: file name must be YYYY-MM-DD-<phase>-<step>-<slug>-<owner>.md "
            "(lowercase slug and owner)"
        )
    data, body = parse_front_matter(path.read_text(encoding="utf-8"), name)
    for key in REQUIRED:
        if key not in data:
            raise EntryError(f"{name}: missing field '{key}'")
    for key in REQUIRED:
        value = data[key]
        if key in LIST_FIELDS:
            if not isinstance(value, tuple):
                raise EntryError(f"{name}: field '{key}' must be a list like [a, b] or []")
        elif not isinstance(value, str) or not value:
            raise EntryError(f"{name}: field '{key}' must be a non-empty value")
    module = str(data["module"])
    if module not in MODULES:
        raise EntryError(f"{name}: field 'module' is '{module}'; allowed: {', '.join(MODULES)}")
    status = str(data["status"])
    if status not in STATUSES:
        raise EntryError(f"{name}: field 'status' is '{status}'; allowed: {', '.join(STATUSES)}")
    phase, step = str(data["phase"]), str(data["step"])
    if match.group("phase").lower() != phase.lower():
        raise EntryError(
            f"{name}: field 'phase' is '{phase}' but the file name says '{match.group('phase')}'"
        )
    if match.group("step") != step:
        raise EntryError(
            f"{name}: field 'step' is '{step}' but the file name says '{match.group('step')}'"
        )
    commits, evals = data["commits"], data["evals"]
    if not isinstance(commits, tuple) or not isinstance(evals, tuple):  # checked above; for mypy
        raise EntryError(f"{name}: 'commits' and 'evals' must be lists")
    return Entry(
        path=path,
        date=match.group("date"),
        phase=phase,
        step=step,
        module=module,
        owner=str(data["owner"]),
        status=status,
        commits=commits,
        evals=evals,
        open_items=_open_items(body),
    )


def parse_module(path: Path) -> Module:
    text = path.read_text(encoding="utf-8")

    def field_value(label: str) -> str:
        match = re.search(rf"^\*\*{label}:\*\*\s*(.+)$", text, flags=re.MULTILINE)
        return match.group(1).strip() if match else "—"

    title = re.search(r"^#\s+(.+)$", text, flags=re.MULTILINE)
    name = title.group(1).strip() if title else path.stem
    return Module(
        name=name,
        path=path,
        owner=field_value("Owner"),
        phases=field_value("Phases"),
        status=field_value("Status"),
    )


def phase_key(phase: str) -> tuple[int, int, str]:
    """Legacy phases (10b, 9e, ...) first, then setup S1/S2, then P0 to P12."""
    if re.fullmatch(r"[Pp]\d+", phase):
        return (2, int(phase[1:]), "")
    if re.fullmatch(r"[Ss]\d+", phase):
        return (1, int(phase[1:]), "")
    digits = re.match(r"\d+", phase)
    return (0, int(digits.group(0)) if digits else 0, phase.lower())


def step_key(step: str) -> tuple[tuple[int, str], ...]:
    return tuple(
        (int(part), "") if part.isdigit() else (0, part) for part in re.split(r"[.]", step)
    )


def load_entries(root: Path) -> list[Entry]:
    folder = root / PROGRESS_DIR / "entries"
    entries = [parse_entry(p) for p in sorted(folder.glob("*.md")) if p.name != "TEMPLATE.md"]
    return sorted(
        entries, key=lambda e: (phase_key(e.phase), step_key(e.step), e.date, e.path.name)
    )


def latest_per_step(entries: list[Entry]) -> list[Entry]:
    """The newest entry (by date, then file name) wins for each (phase, step)."""
    latest: dict[tuple[str, str], Entry] = {}
    for entry in sorted(entries, key=lambda e: (e.date, e.path.name)):
        latest[(entry.phase.upper(), entry.step)] = entry
    return sorted(latest.values(), key=lambda e: (phase_key(e.phase), step_key(e.step)))


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(root: Path) -> str:
    base = root / PROGRESS_DIR
    gates_path = base / "gates.md"
    gates = gates_path.read_text(encoding="utf-8").strip() if gates_path.exists() else ""
    gates = re.sub(r"^#\s+.*\n+", "", gates, count=1)  # drop the file's own title
    modules = [parse_module(base / "modules" / f"{MODULE_FILES[m]}.md") for m in MODULES]
    current = latest_per_step(load_entries(root))

    out: list[str] = [HEADER]
    out.append("\n## Gates\n")
    out.append((gates or "_No gates file (docs/progress/gates.md)._") + "\n")

    out.append("\n## Status by step\n")
    out.append(
        "Latest entry per phase and step. Earlier entries stay in `docs/progress/entries/`.\n"
    )
    if current:
        out.append("\n| Phase | Step | Module | Status | Owner | Date | Commits | Evals | Entry |")
        out.append("\n|---|---|---|---|---|---|---|---|---|")
        for e in current:
            link = f"[{e.path.name}](docs/progress/entries/{e.path.name})"
            out.append(
                f"\n| {_cell(e.phase)} | {_cell(e.step)} | {e.module} | {e.status} "
                f"| {_cell(e.owner)} | {e.date} | {_cell(', '.join(e.commits)) or '—'} "
                f"| {_cell(', '.join(e.evals)) or '—'} | {link} |"
            )
        out.append("\n")
    else:
        out.append("\n_No entries yet._\n")

    out.append("\n## Modules\n")
    out.append("\n| Module | Owner | Phases | Status |")
    out.append("\n|---|---|---|---|")
    for m in modules:
        link = f"[{m.name}](docs/progress/modules/{m.path.name})"
        out.append(f"\n| {link} | {_cell(m.owner)} | {_cell(m.phases)} | {_cell(m.status)} |")
    out.append("\n")

    out.append("\n## Open items\n")
    out.append("From the latest entry of each step. Module-level items live in each module file.\n")
    any_open = False
    for name in MODULES:
        items = [(e, item) for e in current if e.module == name for item in e.open_items]
        if not items:
            continue
        any_open = True
        out.append(f"\n### {name}\n")
        for e, item in items:
            out.append(
                f"\n- {e.phase} {e.step}: {item} ([entry](docs/progress/entries/{e.path.name}))"
            )
        out.append("\n")
    if not any_open:
        out.append("\n_None._\n")

    out.append("\n## History\n")
    out.append(
        "\nEverything up to 18 Nov 2026 (phase log, notes, decisions, open questions) is frozen in "
        "[docs/progress/HISTORY.md](docs/progress/HISTORY.md).\n"
    )
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if PROGRESS.md is stale")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        text = render(args.root)
    except (EntryError, FileNotFoundError) as exc:
        print(f"progress: {exc}", file=sys.stderr)
        return 1
    target = args.root / OUTPUT
    if args.check:
        existing = target.read_text(encoding="utf-8") if target.exists() else ""
        if existing != text:
            print(
                "progress: PROGRESS.md is out of date or was edited by hand. "
                "Run `make progress` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print("progress: PROGRESS.md is current")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"progress: wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
