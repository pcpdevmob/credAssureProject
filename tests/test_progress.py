"""scripts/progress.py: PROGRESS.md is generated from docs/progress/ (README §11)."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("progress", ROOT / "scripts" / "progress.py")
assert _spec and _spec.loader
progress = importlib.util.module_from_spec(_spec)
sys.modules["progress"] = progress  # dataclasses resolve their module through sys.modules
_spec.loader.exec_module(progress)


def _entry(
    *,
    phase: str = "P4",
    step: str = "4.1",
    module: str = "Copilot",
    owner: str = "Suresh",
    status: str = "done",
    commits: str = "[abc1234]",
    body: str = "- Built: headers\n- Open: none\n",
    drop: str | None = None,
) -> str:
    fields = {
        "phase": phase,
        "step": f'"{step}"',
        "module": module,
        "owner": owner,
        "commits": commits,
        "evals": "[E8]",
        "status": status,
    }
    if drop:
        fields.pop(drop)
    head = "\n".join(f"{k}: {v}" for k, v in fields.items())
    return f"---\n{head}\n---\n{body}"


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    base = tmp_path / "docs" / "progress"
    (base / "entries").mkdir(parents=True)
    (base / "modules").mkdir()
    (base / "gates.md").write_text("# Gates\n\n- [x] G2 passed\n", encoding="utf-8")
    for name, stem in progress.MODULE_FILES.items():
        (base / "modules" / f"{stem}.md").write_text(
            f"# {name}\n\n**Owner:** Someone\n**Phases:** P1\n**Status:** ok\n", encoding="utf-8"
        )
    (base / "entries" / "TEMPLATE.md").write_text("not front matter at all", encoding="utf-8")
    return tmp_path


def _write(repo: Path, name: str, text: str) -> None:
    (repo / "docs" / "progress" / "entries" / name).write_text(text, encoding="utf-8")


def test_latest_entry_wins_per_step(repo: Path) -> None:
    _write(
        repo,
        "2026-11-19-p4-4.1-headers-suresh.md",
        _entry(status="in_progress", commits="[aaa1111]"),
    )
    _write(repo, "2026-11-20-p4-4.1-headers-suresh.md", _entry(status="done", commits="[bbb2222]"))
    out = progress.render(repo)
    assert "bbb2222" in out
    assert "aaa1111" not in out
    assert out.count("| P4 | 4.1 |") == 1


def test_output_is_deterministic_and_sorted(repo: Path) -> None:
    _write(
        repo,
        "2026-11-21-p10-10.1-ship-pritish.md",
        _entry(phase="P10", step="10.1", module="Deployment"),
    )
    _write(repo, "2026-11-19-p4-4.2-glossary-suresh.md", _entry(step="4.2"))
    _write(
        repo,
        "2026-11-18-s1-1-progress-pritish.md",
        _entry(phase="S1", step="1", module="Documentation"),
    )
    first = progress.render(repo)
    assert first == progress.render(repo)
    assert first.index("| S1 | 1 |") < first.index("| P4 | 4.2 |") < first.index("| P10 | 10.1 |")


def test_template_is_ignored_and_open_items_collected(repo: Path) -> None:
    _write(
        repo,
        "2026-11-19-p4-4.4-gate-suresh.md",
        _entry(step="4.4", body="- Open: tune on dev split\n- Open: none\n"),
    )
    out = progress.render(repo)
    assert "entries/TEMPLATE.md" not in out  # skipped, though it is not a valid entry
    assert "P4 4.4: tune on dev split" in out
    assert out.startswith("<!-- GENERATED by make progress")


@pytest.mark.parametrize(
    ("name", "text", "message"),
    [
        ("2026-11-19-p4-4.1-x-suresh.md", _entry(drop="owner"), "missing field 'owner'"),
        (
            "2026-11-19-p4-4.1-x-suresh.md",
            _entry(module="Retrieval"),
            "field 'module' is 'Retrieval'",
        ),
        (
            "2026-11-19-p4-4.1-x-suresh.md",
            _entry(status="finished"),
            "field 'status' is 'finished'",
        ),
        (
            "2026-11-19-p4-4.1-x-suresh.md",
            _entry(commits="abc1234"),
            "field 'commits' must be a list",
        ),
        ("2026-11-19-p4-4.2-x-suresh.md", _entry(step="4.1"), "field 'step' is '4.1'"),
        ("p4-4.1-headers.md", _entry(), "file name must be"),
        ("2026-11-19-P4-4.1-X-Suresh.md", _entry(), "file name must be"),
    ],
)
def test_invalid_entries_name_file_and_field(
    repo: Path, name: str, text: str, message: str
) -> None:
    _write(repo, name, text)
    with pytest.raises(progress.EntryError, match=message) as info:
        progress.render(repo)
    assert name in str(info.value)


def test_check_fails_on_hand_edit_and_passes_after_regenerate(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    _write(repo, "2026-11-19-p4-4.1-headers-suresh.md", _entry())
    assert progress.main(["--root", str(repo)]) == 0
    assert progress.main(["--root", str(repo), "--check"]) == 0
    target = repo / "PROGRESS.md"
    target.write_text(target.read_text(encoding="utf-8") + "\nhand edit\n", encoding="utf-8")
    assert progress.main(["--root", str(repo), "--check"]) == 1
    assert "make progress" in capsys.readouterr().err


def test_check_fails_on_invalid_entry(repo: Path) -> None:
    _write(repo, "2026-11-19-p4-4.1-headers-suresh.md", _entry(status="nope"))
    assert progress.main(["--root", str(repo), "--check"]) == 1


def test_repository_progress_is_current() -> None:
    """The committed PROGRESS.md matches the generator (the rule pre-push and CI apply)."""
    assert progress.main(["--root", str(ROOT), "--check"]) == 0
