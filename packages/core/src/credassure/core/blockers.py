"""Closed blocker catalogue (scope #9, design-detail §2.4).

A warning never decides a gate. ``NEEDS_INPUT`` asks one question. Every other code is a gate.
"""

from enum import StrEnum


class BlockerCode(StrEnum):
    ONB_ROLE_NOT_AUTHORISED = "ONB_ROLE_NOT_AUTHORISED"
    ONB_TRAINING_EXPIRED = "ONB_TRAINING_EXPIRED"
    ONB_TRAINING_INCOMPLETE = "ONB_TRAINING_INCOMPLETE"
    ONB_TRAINING_MISSING = "ONB_TRAINING_MISSING"
    ONB_ACK_MISSING = "ONB_ACK_MISSING"
    ONB_ACK_OLD_VERSION = "ONB_ACK_OLD_VERSION"
    WC_MISSING_FIELD = "WC_MISSING_FIELD"
    WC_CONFLICT_TOTALS = "WC_CONFLICT_TOTALS"
    WC_DUPLICATE_ID = "WC_DUPLICATE_ID"
    WC_UNIT_OR_CURRENCY = "WC_UNIT_OR_CURRENCY"
    WC_DATE_OUT_OF_RANGE = "WC_DATE_OUT_OF_RANGE"
    WC_UNSOURCED_OFFSET = "WC_UNSOURCED_OFFSET"
    WC_MSE_PAYABLE_OVER_45D = "WC_MSE_PAYABLE_OVER_45D"
    LW_OFFER_INVALID = "LW_OFFER_INVALID"
    LW_MISSING_MATERIAL_TERM = "LW_MISSING_MATERIAL_TERM"
    LW_INSTALMENT_MISMATCH = "LW_INSTALMENT_MISMATCH"
    LW_SCHEDULE_DATE_MISMATCH = "LW_SCHEDULE_DATE_MISMATCH"  # ADR 0021
    LW_HIDDEN_CHARGE = "LW_HIDDEN_CHARGE"
    LW_NOT_AFFORDABLE = "LW_NOT_AFFORDABLE"
    LW_LATE_OR_SHORT = "LW_LATE_OR_SHORT"
    LW_RATE_MAY_RESET = "LW_RATE_MAY_RESET"
    LW_BENCHMARK_NOT_EXTERNAL = "LW_BENCHMARK_NOT_EXTERNAL"
    LW_CGTMSE_INELIGIBLE = "LW_CGTMSE_INELIGIBLE"
    LW_FEWER_THAN_TWO_ELIGIBLE = "LW_FEWER_THAN_TWO_ELIGIBLE"
    VER_UNMATCHED_NUMBER = "VER_UNMATCHED_NUMBER"
    VER_BAD_CITATION = "VER_BAD_CITATION"
    VER_SUPERSEDED_SOURCE = "VER_SUPERSEDED_SOURCE"
    VER_BANNED_CONTENT = "VER_BANNED_CONTENT"
    VER_PII = "VER_PII"
    VER_REPORT_INCOMPLETE = "VER_REPORT_INCOMPLETE"
    SUP_UPSTREAM_NOT_GO = "SUP_UPSTREAM_NOT_GO"
    SUP_BUDGET_EXCEEDED = "SUP_BUDGET_EXCEEDED"
    SUP_SCHEMA_INVALID = "SUP_SCHEMA_INVALID"
    SUP_ROUTE_HELD = "SUP_ROUTE_HELD"
    SUP_AGENT_ERROR = "SUP_AGENT_ERROR"
    SUP_RETURN_NO_PENDING_APPROVAL = "SUP_RETURN_NO_PENDING_APPROVAL"


class BlockerEffect(StrEnum):
    GATE = "gate"
    WARNING = "warning"
    NEEDS_INPUT = "needs_input"


_WARNINGS = frozenset(
    {
        BlockerCode.WC_MSE_PAYABLE_OVER_45D,
        BlockerCode.LW_RATE_MAY_RESET,
        BlockerCode.LW_BENCHMARK_NOT_EXTERNAL,
        BlockerCode.LW_CGTMSE_INELIGIBLE,
    }
)
_NEEDS_INPUT = frozenset({BlockerCode.ONB_TRAINING_MISSING})


def blocker_effect(code: BlockerCode) -> BlockerEffect:
    """How the Supervisor treats this code. Warnings do not flip a gate."""
    if code in _WARNINGS:
        return BlockerEffect.WARNING
    if code in _NEEDS_INPUT:
        return BlockerEffect.NEEDS_INPUT
    return BlockerEffect.GATE
